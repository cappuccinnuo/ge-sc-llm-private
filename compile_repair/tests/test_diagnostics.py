"""CP3 message families and unchanged constraint semantics; no corpus dependency."""
from pathlib import Path
import pytest
from compile_repair.toolchain.solc import (parse_diagnostics, classify_diagnostic,
    classify_constraints, classify_slither, pragma_evidence, lexical_tokens)
from compile_repair.rules.environment import pragma_interval
from scripts.DFG.models import Unsupported

F = Path(__file__).parent / "fixtures/cp3_diagnostics"

@pytest.mark.parametrize("name,message,category", [
 ("missing_semicolon", "Expected token Semicolon got 'RBrace'", "unbalanced_structure"),
 ("missing_semicolon", "Expected ';' but got '}'", "unbalanced_structure"),
 ("truncated", "Expected primary expression.", "unbalanced_structure"),
 ("warning", "Expected identifier but got 'contract'", "parser_error_other"),
 ("duplicate_contract", "Identifier already declared.", "duplicate_definition"),
 ("duplicate_function", "Function with same name and parameter types defined twice.", "duplicate_definition"),
 ("duplicate_license", "Multiple SPDX license identifiers found in source file.", "multiple_license_or_pragma"),
 ("duplicate_abicoder", "ABI coder has already been selected for this source unit.", "multiple_license_or_pragma"),
 ("undeclared", "Undeclared identifier.", "undeclared_identifier"),
 ("type_mismatch", "Type int_const 1 is not implicitly convertible to expected type bool.", "type_error_other"),
 ("docstring", 'Documented parameter "absent" not found in parameter list.', "docstring_error"),
 ("syntax", '"continue" has to be in a "for" or "while" loop.', "syntax_error"),
 ("encoding", "Invalid token.", "encoding"),
 ("stack_deep", "Stack too deep, try removing local variables.", "codegen_only"),
 ("warning", "Some future unknown compiler diagnostic.", "other"),
])
@pytest.mark.parametrize("modern", [False, True])
def test_observed_message_categories(name, message, category, modern):
    stderr = ("Error: "+message+"\n --> a.sol:2:3:\n" if modern else "a.sol:2:3: Error: "+message+"\n")
    diagnostic = parse_diagnostics(stderr)[0]
    assert diagnostic["kind"] == "Error" and diagnostic["error_code"] is None
    assert diagnostic["location_format"] == ("modern" if modern else "legacy")
    assert classify_diagnostic(diagnostic, (F/(name+".sol")).read_bytes())["category"] == category

@pytest.mark.parametrize("kind,category", [
 ("JSONError","json_error"), ("IOError","io_error"), ("ParserError","parser_error_other"),
 ("DocstringParsingError","docstring_error"), ("SyntaxError","syntax_error"),
 ("DeclarationError","declaration_error"), ("TypeError","type_error_other"),
 ("UnimplementedFeatureError","unimplemented_feature"), ("InternalCompilerError","internal_compiler_error"),
 ("Exception","compiler_exception"), ("CompilerError","other"), ("FatalError","fatal_error"),
 ("Warning","warning")])
def test_documented_types_without_fabricating_compiler_crashes(kind, category):
    # Synthetic interface diagnostics cover documented families whose compiler
    # crashes cannot responsibly/reliably be generated by a Solidity mutation.
    diagnostic = parse_diagnostics(kind+": diagnostic family fixture")[0]
    result = classify_diagnostic(diagnostic, (F/"warning.sol").read_bytes())
    assert result["category"] == category
    assert result["failure"] == (kind != "Warning")

def test_primary_location_notes_no_location_and_warnings():
    text = ("Warning: harmless\n--> a.sol\n\nError: Identifier already declared.\n"
            " --> dir/a.sol:2:5:\nNote: other declaration\n --> dir/b.sol:90:8:\n"
            "Error: no location supplied\n")
    rows = parse_diagnostics(text)
    assert len(rows) == 3
    assert rows[0]["filename"] is None and rows[0]["location_format"] == "absent"
    assert (rows[1]["filename"], rows[1]["line"], rows[1]["column"]) == ("dir/a.sol",2,5)
    assert rows[2]["filename"] is None

def test_exception_detail_and_stack_deep_legacy():
    rows = parse_diagnostics("Compiler error (CompilerUtils.cpp:1420): Stack too deep.\n")
    assert classify_diagnostic(rows[0])["category"] == "codegen_only"
    rows = parse_diagnostics("Unimplemented feature:\nstd::exception::what: cannot compile this\n")
    assert "cannot compile this" in rows[0]["message"]
    assert classify_diagnostic(rows[0])["category"] == "unimplemented_feature"

def test_located_base_is_not_an_arbitrary_missing_identifier():
    raw = (F/"missing_base.sol").read_bytes()
    offset = raw.index(b"Missing")
    row = raw[:offset].count(b"\n")+1
    column = offset-raw.rfind(b"\n",0,offset)
    d = parse_diagnostics("a.sol:%d:%d: Error: Identifier not found or not unique."%(row,column))[0]
    assert classify_diagnostic(d,raw)["category"] == "missing_base_contract"
    assert classify_diagnostic(dict(d,line=None),raw)["category"] == "undeclared_identifier"

@pytest.mark.parametrize("name,category", [("package_import","unresolved_package_import"),
                                         ("relative_import","missing_relative_file")])
def test_import_category_requires_located_original_literal(name, category):
    raw = (F/(name+".sol")).read_bytes(); offset=raw.index(b"import")
    row=raw[:offset].count(b"\n")+1; column=offset-raw.rfind(b"\n",0,offset)
    diagnostic=parse_diagnostics('a.sol:%d:%d: Error: Source "Absent.sol" not found: File not found.'%(row,column))[0]
    assert classify_diagnostic(diagnostic,raw)["category"] == category
    assert classify_diagnostic(dict(diagnostic,line=None),raw)["category"] == "io_error"

@pytest.mark.parametrize("name,category", [("union","unsupported_disjunction"),
 ("unsupported_expression","unsupported_expression"), ("unterminated","unterminated_pragma"),
 ("swallowed_directive","pragma_missing_semicolon_candidate"),
 ("conflicting_pragma","closure_version_conflict")])
def test_unsupported_subdivision_preserves_frozen_reader(name, category):
    raw=(F/(name+".sol")).read_bytes()
    with pytest.raises(Unsupported) as failure: pragma_interval([raw])
    result=classify_constraints(str(failure.value),[raw])
    assert result["category"] == category
    for row in result["pragma_evidence"]:
        assert bytes.fromhex(row["expression_hex"]) == raw[row["start"]:row["end"]]

def test_unit_intersection_and_swallowed_keywords():
    result=classify_constraints("F: empty pragma intersection across compilation unit",[
        b"pragma solidity ^0.4.12;",b"pragma solidity ^0.5.0;"])
    assert result["subtype"] == "compilation_unit"
    for word in [b"import", b"pragma", b"contract", b"interface", b"library", b"abstract"]:
        raw=b"pragma solidity ^0.8.0\n"+word+b" next;"
        result=classify_constraints("F: unsupported pragma expression",[raw])
        assert result["category"] == "pragma_missing_semicolon_candidate"

def test_comments_strings_are_not_constraint_or_structure_evidence():
    raw=b'// pragma solidity 0.1;\ncontract C { string s="pragma solidity any; {("; }'
    assert pragma_evidence(raw) == []
    assert not any(t==b"pragma" for _,_,k,t in lexical_tokens(raw))
    d=parse_diagnostics("Error: Expected an identifier")[0]
    assert classify_diagnostic(d,raw)["category"] == "parser_error_other"

def test_slither_tuple_is_candidate_not_implemented_rewrite():
    raw=(F/"tuple_call.sol").read_bytes()
    candidate=classify_slither({"exception_type":"AssertionError","version":"0.4.24"},[raw])
    assert candidate["repair_route"] == "tuple_call_equivalence_candidate"
    assert candidate["candidate_source_indexes"] == [0]
    assert classify_slither({"exception_type":"AssertionError","version":"0.8.38"},[raw])["repair_route"] == "tool_limitation"
    assert classify_slither({"d3":False,"d3_a":False})["subtype"] == "d3_incomplete"

